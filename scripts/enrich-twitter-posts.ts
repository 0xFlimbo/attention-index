function readDataFile<T>(fileName: string): T {
  return JSON.parse(readFileSync(resolve(DATA_DIR, fileName), "utf-8")) as T;
}

/** posts.json / amplifications.json currently ship with no trailing newline — preserved on write. */
function writeDataFile(fileName: string, data: unknown): void {
  writeFileSync(resolve(DATA_DIR, fileName), JSON.stringify(data, null, 2));
}

function backupDataFiles(): string {
  const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
  const backupDir = resolve(CACHE_DIR, "backups", timestamp);
  mkdirSync(backupDir, { recursive: true });
  for (const fileName of ["posts.json", "amplifications.json"]) {
    writeFileSync(resolve(backupDir, fileName), readFileSync(resolve(DATA_DIR, fileName)));
  }
  return backupDir;
}

function writeCache(payload: unknown): void {
  mkdirSync(CACHE_DIR, { recursive: true });
  writeFileSync(CACHE_FILE, JSON.stringify(payload, null, 2));
}

