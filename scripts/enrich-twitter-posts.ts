interface ReferencedTweet {
  type: "quoted" | "replied_to" | "retweeted";
  id: string;
}

interface ApiTweet {
  id: string;
  author_id?: string;
  created_at?: string;
  text: string;
  note_tweet?: { text: string };
  referenced_tweets?: ReferencedTweet[];
}

interface ApiUser {
  id: string;
  username: string;
  name: string;
}

interface ApiError {
  value?: string;
  detail?: string;
  title?: string;
}

interface TweetLookupResponse {
  data?: ApiTweet[];
  includes?: { users?: ApiUser[] };
  errors?: ApiError[];
}

// ---------------------------------------------------------------------------
// Fetch helpers
// ---------------------------------------------------------------------------

function extractStatusId(url: string): string | null {
  const match = url.match(/status\/(\d+)/);
  return match ? (match[1] ?? null) : null;
}

function chunk<T>(items: T[], size: number): T[][] {
  const chunks: T[][] = [];
  for (let i = 0; i < items.length; i += size) chunks.push(items.slice(i, i + size));
  return chunks;
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolvePromise) => setTimeout(resolvePromise, ms));
}

/**
 * Fetches one batch (<=100 ids) of tweets. Retries only on 429/5xx, respecting
 * `x-rate-limit-reset` / `retry-after` headers. Any other non-2xx status
 * (notably 401/403 — the Free X API tier does not permit tweet lookup) is
 * reported verbatim and thrown immediately: never retried, never worked around.
 */
async function fetchTweetBatch(ids: string[], token: string): Promise<TweetLookupResponse> {
  const url = `${X_API_URL}?ids=${ids.join(",")}&tweet.fields=${TWEET_FIELDS}&expansions=${EXPANSIONS}&user.fields=${USER_FIELDS}`;

  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    let response: Response;
    try {
      response = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
    } catch (error) {
      if (attempt === MAX_RETRIES) throw new Error(`network error: ${(error as Error).message}`);
      await sleep(1000 * 2 ** attempt);
      continue;
    }

    if (response.ok) {
      return (await response.json()) as TweetLookupResponse;
    }

    const retryable = response.status === 429 || response.status >= 500;
    const bodyText = await response.text().catch(() => "");

    if (!retryable || attempt === MAX_RETRIES) {
      throw new FetchFailure(response.status, response.statusText, bodyText);
    }

    const resetHeader = response.headers.get("x-rate-limit-reset");
    const retryAfterHeader = response.headers.get("retry-after");
    let waitMs = 1000 * 2 ** attempt;
    if (resetHeader) {
      const resetAtMs = Number(resetHeader) * 1000;
      const untilReset = resetAtMs - Date.now();
      if (Number.isFinite(untilReset) && untilReset > 0) waitMs = Math.min(untilReset, 60_000);
    } else if (retryAfterHeader) {
      const seconds = Number(retryAfterHeader);
      if (Number.isFinite(seconds) && seconds > 0) waitMs = seconds * 1000;
    }
    console.error(
      `  fetch attempt ${attempt + 1} failed with HTTP ${response.status}; retrying in ${Math.round(waitMs / 1000)}s`,
    );
    await sleep(waitMs);
  }

  // Unreachable — the loop always returns or throws — but keeps TypeScript satisfied.
  throw new Error("fetchTweetBatch: exhausted retries without a terminal result");
}

class FetchFailure extends Error {
  constructor(
    public status: number,
    public statusText: string,
    public body: string,
  ) {
    super(`HTTP ${status} ${statusText}`);
  }
}

