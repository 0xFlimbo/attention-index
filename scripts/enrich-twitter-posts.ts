// Main
// ---------------------------------------------------------------------------

async function main(): Promise<void> {
  const token = loadBearerToken();

  if (refreshMetrics) {
    // Still unimplemented — the refresh itself is docs/WORKPLAN.md B12. What
    // changed at B18 is that the contract it has to honour now exists, so
    // B12 has nothing left to invent: a refresh **appends** an observation to
    // `post.observations`, never replaces one, and the appended reading
    // carries `source: "api"` because that is where this script reads from.
    // The stored history must stay chronological and must not gain a second
    // reading for a date it already holds (docs/DATA.md §5).
    console.log(
      "--refresh-metrics was passed, but the refresh itself is not implemented yet " +
        "(docs/WORKPLAN.md B12). No observation will be appended. The contract it must " +
        'follow is in docs/DATA.md §5: append, never replace, with source "api".',
    );
  }

  // Loaded as raw JSON (not the zod-parsed/normalized shape) so untouched records are
  // written back byte-for-byte identical — schemas below are used only to *validate*,
  // never as the source of the object we persist (zod's nullish->null transforms would
  // otherwise inject keys real records currently omit, e.g. amplification follower_count).
  const posts = readDataFile<Post[]>("posts.json");
  const amplifications = readDataFile<Amplification[]>("amplifications.json");
  if (!postsFileSchema.safeParse(posts).success) {
    console.error("data/posts.json failed schema validation — run `pnpm validate:data` first. Aborting.");
    process.exit(1);
  }
  if (!amplificationsFileSchema.safeParse(amplifications).success) {
    console.error("data/amplifications.json failed schema validation — run `pnpm validate:data` first. Aborting.");
    process.exit(1);
  }

  const postIds = posts.map((post) => extractStatusId(post.url)).filter((id): id is string => id !== null);
  const ampIds = amplifications
    .map((amp) => extractStatusId(amp.evidence_url))
    .filter((id): id is string => id !== null);

  console.log(`Fetching ${postIds.length} post tweet(s) and ${ampIds.length} amplification evidence tweet(s)...`);

  let postsResponses: TweetLookupResponse[];
  let ampsResponses: TweetLookupResponse[];
  try {
    postsResponses = await Promise.all(chunk(postIds, 100).map((batch) => fetchTweetBatch(batch, token)));
    ampsResponses = await Promise.all(chunk(ampIds, 100).map((batch) => fetchTweetBatch(batch, token)));
  } catch (error) {
    if (error instanceof FetchFailure) {
      console.error(`\nX API request failed: HTTP ${error.status} ${error.statusText}`);
      console.error(`Response body: ${error.body}`);
      console.error(
        "\nThis is a likely outcome on the X API Free access tier, which does not permit tweet lookup " +
          "(GET /2/tweets). No retry loop, no workaround, and no invented content — data/*.json was not touched.",
      );
    } else {
      console.error(`\nEnrichment failed: ${(error as Error).message}`);
      console.error("data/*.json was not touched.");
    }
    process.exit(1);
  }

  writeCache({
    fetched_at: new Date().toISOString(),
    posts: postsResponses,
    amplifications: ampsResponses,
  });
  console.log(`Cached raw API responses to ${CACHE_FILE} (gitignored, never merged into canonical data).`);

  const tweetsById = new Map<string, ApiTweet>();
  const usersById = new Map<string, ApiUser>();
  const apiErrorsById = new Map<string, ApiError>();
  for (const response of [...postsResponses, ...ampsResponses]) {
    for (const tweet of response.data ?? []) tweetsById.set(tweet.id, tweet);
    for (const user of response.includes?.users ?? []) usersById.set(user.id, user);
    for (const err of response.errors ?? []) if (err.value) apiErrorsById.set(err.value, err);
  }

  const trackedStatusIdToPostId = new Map<string, string>();
  for (const post of posts) {
    const statusId = extractStatusId(post.url);
    if (statusId) trackedStatusIdToPostId.set(statusId, post.id);
  }

  // --- Posts ---------------------------------------------------------------

  const PENDING_NOTE = "Post content/title enrichment pending.";
  const updatedPosts: Post[] = [];
  const postReport: string[] = [];

  for (const post of posts) {
    const statusId = extractStatusId(post.url);
    if (!statusId) {
      postReport.push(`${post.id}: could not extract a tweet id from url — skipped.`);
      updatedPosts.push(post);
      continue;
    }

    const tweet = tweetsById.get(statusId);
    if (!tweet) {
      const apiError = apiErrorsById.get(statusId);
      postReport.push(
        `${post.id} (tweet ${statusId}): NOT RETURNED by API` +
          (apiError?.detail ? ` — ${apiError.detail}` : "") +
          ". Flagged for manual review; record left unchanged.",
      );
      updatedPosts.push(post);
      continue;
    }

    let next: Post = { ...post };
    const changes: string[] = [];

    // published_at — only corrected if the API contradicts the stored date.
    if (tweet.created_at) {
      const apiDate = tweet.created_at.slice(0, 10);
      if (apiDate !== next.published_at) {
        changes.push(`published_at: "${next.published_at}" -> "${apiDate}" (API created_at contradicts stored date)`);
        next = { ...next, published_at: apiDate };
      }
    }

    const enrichment = POST_ENRICHMENTS[post.id];
    if (enrichment) {
      changes.push(`title: "${next.title}" -> "${enrichment.title}"`);
      changes.push(`subject: ${JSON.stringify(next.subject)} -> ${JSON.stringify(enrichment.subject)}`);
      changes.push(`summary: ${JSON.stringify(next.summary)} -> ${JSON.stringify(enrichment.summary)}`);
      changes.push(`tags: ${JSON.stringify(next.tags)} -> ${JSON.stringify(enrichment.tags)}`);
      next = {
        ...next,
        title: enrichment.title,
        subject: enrichment.subject,
        summary: enrichment.summary,
        tags: enrichment.tags,
      };
      if (next.notes === PENDING_NOTE) {
        changes.push(`notes: ${JSON.stringify(next.notes)} -> null`);
        next = { ...next, notes: null };
      }
    } else if (post.notes === PENDING_NOTE) {
      const reason = FLAGGED_POSTS[post.id] ?? "No curated enrichment available for this post.";
      postReport.push(`${post.id} (tweet ${statusId}): FLAGGED FOR MANUAL REVIEW — ${reason}`);
    }

    if (changes.length > 0) {
      const validation = postSchema.safeParse(next);
      if (!validation.success) {
        postReport.push(
          `${post.id} (tweet ${statusId}): proposed changes FAILED validation, record left unchanged: ` +
            validation.error.issues.map((issue) => issue.message).join("; "),
        );
        updatedPosts.push(post);
        continue;
      }
      postReport.push(`${post.id} (tweet ${statusId}): OK — ${changes.join(" | ")}`);
      updatedPosts.push(next);
    } else {
      postReport.push(`${post.id} (tweet ${statusId}): confirmed, no changes needed.`);
      updatedPosts.push(post);
    }
  }

  // --- Amplifications --------------------------------------------------------

  const REFERENCED_TYPE_TO_ACTION: Record<ReferencedTweet["type"], Amplification["action"]> = {
    quoted: "quote_post",
    replied_to: "reply",
    retweeted: "repost",
  };

  const updatedAmplifications: Amplification[] = [];
  const ampReport: string[] = [];
  const promotionCandidates: string[] = [];

  for (const amp of amplifications) {
    const statusId = extractStatusId(amp.evidence_url);
    if (!statusId) {
      ampReport.push(`${amp.id}: could not extract a tweet id from evidence_url — skipped.`);
      updatedAmplifications.push(amp);
      continue;
    }

    const tweet = tweetsById.get(statusId);
    if (!tweet) {
      const apiError = apiErrorsById.get(statusId);
      ampReport.push(
        `${amp.id} (tweet ${statusId}): NOT RETURNED by API` +
          (apiError?.detail ? ` — ${apiError.detail}` : "") +
          ". Flagged for manual review; record left unchanged.",
      );
      updatedAmplifications.push(amp);
      continue;
    }

    let next: Amplification = { ...amp };
    const changes: string[] = [];
    const confirmations: string[] = [];

    // account / date confirmation (never auto-changed — only reported).
    const author = tweet.author_id ? usersById.get(tweet.author_id) : undefined;
    if (author) {
      const apiHandle = `@${author.username}`;
      if (amp.account && amp.account.toLowerCase() !== apiHandle.toLowerCase()) {
        ampReport.push(
          `${amp.id}: account mismatch — stored "${amp.account}", API says "${apiHandle}". Not auto-changed; flagged.`,
        );
      } else {
        confirmations.push(`account confirmed (${apiHandle})`);
      }
    }
    if (tweet.created_at) {
      const apiDate = tweet.created_at.slice(0, 10);
      if (apiDate !== amp.date) {
        ampReport.push(`${amp.id}: date mismatch — stored "${amp.date}", API says "${apiDate}". Not auto-changed; flagged.`);
      } else {
        confirmations.push("date confirmed");
      }
    }

    // action / related_post_id — derived directly from referenced_tweets.
    const firstReference = (tweet.referenced_tweets ?? []).find((ref) => ref.type in REFERENCED_TYPE_TO_ACTION);
    if (!firstReference) {
      ampReport.push(
        `${amp.id} (tweet ${statusId}): API returned no referenced_tweets — action/related_post_id not ` +
          `auto-confirmable from this evidence. Left as "${amp.action}"/${JSON.stringify(amp.related_post_id)}.`,
      );
    } else {
      const derivedAction = REFERENCED_TYPE_TO_ACTION[firstReference.type];
      const derivedRelatedPostId = trackedStatusIdToPostId.get(firstReference.id) ?? null;

      if (derivedAction !== amp.action) {
        changes.push(`action: "${amp.action}" -> "${derivedAction}" (API referenced_tweets: ${firstReference.type})`);
        next = { ...next, action: derivedAction };
      }
      if (derivedRelatedPostId !== amp.related_post_id) {
        changes.push(
          `related_post_id: ${JSON.stringify(amp.related_post_id)} -> ${JSON.stringify(derivedRelatedPostId)} ` +
            `(quoted/replied/retweeted tweet is ${firstReference.id}` +
            (derivedRelatedPostId ? `, a tracked post` : ", not a currently tracked post") +
            ")",
        );
        next = { ...next, related_post_id: derivedRelatedPostId };
      }

      if (changes.length === 0) {
        confirmations.push(`action and related_post_id confirmed (${derivedAction})`);
      } else {
        // Append the confirming evidence to the existing note rather than replacing it —
        // the prior investigatory note stays on record.
        const noteAddendum =
          `X API confirms: ${firstReference.type} of status ${firstReference.id}` +
          (derivedRelatedPostId ? ` (${derivedRelatedPostId}).` : " (not currently a tracked post).");
        next = { ...next, notes: amp.notes ? `${amp.notes} ${noteAddendum}` : noteAddendum };
        changes.push(`notes updated to record the confirmed evidence`);
      }
    }

    if (changes.length > 0) {
      const validation = amplificationSchema.safeParse(next);
      if (!validation.success) {
        ampReport.push(
          `${amp.id} (tweet ${statusId}): proposed changes FAILED validation, record left unchanged: ` +
            validation.error.issues.map((issue) => issue.message).join("; "),
        );
        updatedAmplifications.push(amp);
        continue;
      }
      ampReport.push(`${amp.id} (tweet ${statusId}): OK — ${changes.join(" | ")}`);
      updatedAmplifications.push(next);
      if (next.status === "needs_review") {
        promotionCandidates.push(
          `${amp.id}: now has evidence-confirmed action "${next.action}"` +
            (next.related_post_id ? ` linked to ${next.related_post_id}` : "") +
            " — status left as needs_review; promotion is the maintainer's decision.",
        );
      }
    } else {
      ampReport.push(`${amp.id} (tweet ${statusId}): ${confirmations.join(", ") || "confirmed, no changes needed."}`);
      updatedAmplifications.push(amp);
      if (amp.status === "needs_review" && firstReference) {
        promotionCandidates.push(
          `${amp.id}: action "${amp.action}" already matches confirmed API evidence` +
            (amp.related_post_id ? ` (linked to ${amp.related_post_id})` : "") +
            " — status left as needs_review; promotion is the maintainer's decision.",
        );
      }
    }
  }

  // --- Report ----------------------------------------------------------------

  console.log("\n=== Posts ===");
  for (const line of postReport) console.log(`  ${line}`);

  console.log("\n=== Amplifications ===");
  for (const line of ampReport) console.log(`  ${line}`);

  if (promotionCandidates.length > 0) {
    console.log("\n=== Promotion candidates (maintainer decision — not applied) ===");
    for (const line of promotionCandidates) console.log(`  ${line}`);
  }

  const postsChanged = JSON.stringify(posts) !== JSON.stringify(updatedPosts);
  const ampsChanged = JSON.stringify(amplifications) !== JSON.stringify(updatedAmplifications);

  if (isDryRun) {
    console.log(`\n--dry-run: no files written. posts changed: ${postsChanged}; amplifications changed: ${ampsChanged}.`);
    return;
  }

  if (!postsChanged && !ampsChanged) {
    console.log("\nNo changes to write.");
    return;
  }

  const backupDir = backupDataFiles();
  console.log(`\nBacked up data/posts.json and data/amplifications.json to ${backupDir}`);

  if (postsChanged) {
    writeDataFile("posts.json", updatedPosts);
    console.log("Wrote data/posts.json");
  }
  if (ampsChanged) {
    writeDataFile("amplifications.json", updatedAmplifications);
    console.log("Wrote data/amplifications.json");
  }
}

main().catch((error) => {
  console.error(`Unexpected error: ${(error as Error).message}`);
  process.exit(1);
});
