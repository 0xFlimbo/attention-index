/**
 * pnpm enrich:twitter [-- --dry-run] [-- --refresh-metrics]
 *
 * NOTE (B18): post readings live in `post.observations`, an append-only
 * history. This script does not write them today; when `--refresh-metrics`
 * is implemented (B12) it appends one observation with `source: "api"`
 * rather than overwriting the previous reading.
 *
 * One-time / occasional maintenance tool (docs/ENGINEERING.md §12). Never called
 * during `next build`, rendering, or CI.
 *
 * Fetches public tweet data for the posts already in `data/posts.json` and the
 * amplification evidence URLs in `data/amplifications.json` via the X API v2
 * tweet-lookup endpoint, then:
 *
 *  - posts: fills in `title` / `subject` / `summary` / `tags` for records the
 *    maintainer has curated in POST_ENRICHMENTS below (docs/DATA.md §5,
 *    docs/EDITORIAL.md §5 — this copy is authored by a human reading the fetched
 *    tweet text, never generated by this script), corrects `published_at` only
 *    if the API's `created_at` contradicts the stored date, and clears the
 *    `"Post content/title enrichment pending."` notes marker on records it
 *    successfully enriches.
 *  - amplifications: derives `action` and `related_post_id` directly from the
 *    API's `referenced_tweets` field (quoted -> quote_post, replied_to -> reply,
 *    retweeted -> repost) and confirms `entity_name` / `account` / `date`
 *    against the fetched tweet. Never promotes `status`.
 *
 * Never invents content: a post whose meaning depends on an image or quoted
 * tweet this tool cannot see is left untouched and flagged (see FLAGGED_POSTS).
 * A tweet the API cannot return (deleted/protected/not found) is flagged, never
 * guessed.
 *
 * Credentials: `X_BEARER_TOKEN` is read from `.env.local` and is never logged,
 * echoed, or written anywhere, including in error output.
 */
